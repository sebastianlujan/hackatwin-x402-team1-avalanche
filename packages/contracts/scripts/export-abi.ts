import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export interface AbiArtifact {
  key: string;
  abi: unknown[];
}

interface ForgeArtifact {
  abi?: unknown[];
  metadata?: { settings?: { compilationTarget?: Record<string, string> } };
}

function jsonFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === 'build-info' ? [] : jsonFiles(path);
    return entry.name.endsWith('.json') ? [path] : [];
  });
}

const byKey = (a: AbiArtifact, b: AbiArtifact) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0);

export function collectArtifacts(outDir: string): AbiArtifact[] {
  const found = new Map<string, unknown[]>();
  for (const file of jsonFiles(outDir)) {
    const artifact = JSON.parse(readFileSync(file, 'utf8')) as ForgeArtifact;
    const target = artifact.metadata?.settings?.compilationTarget;
    if (!artifact.abi || !target) continue;
    for (const [source, name] of Object.entries(target)) {
      if (source.startsWith('src/')) found.set(`${source}:${name}`, artifact.abi);
    }
  }
  return [...found].map(([key, abi]) => ({ key, abi })).sort((a, b) => byKey(a, b));
}

export function buildAbiModule(artifacts: AbiArtifact[]): string {
  const header = '// Generated by scripts/export-abi.ts. Do not edit.\n';
  if (artifacts.length === 0) return `${header}export const abis = {} as const;\n`;
  const entries = [...artifacts]
    .sort((a, b) => byKey(a, b))
    .map(({ key, abi }) => `  '${key}': ${JSON.stringify(abi, null, 2).replaceAll('\n', '\n  ')},`);
  return `${header}export const abis = {\n${entries.join('\n')}\n} as const;\n`;
}

export function exportAbi(outDir: string, destination: string): void {
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, buildAbiModule(collectArtifacts(outDir)));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  exportAbi(join(packageDir, 'out'), join(packageDir, 'abi', 'generated', 'abis.ts'));
}
